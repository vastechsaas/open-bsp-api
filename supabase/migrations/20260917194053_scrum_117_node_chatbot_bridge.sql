CREATE OR REPLACE FUNCTION public.record_node_chatbot_handoff(p_organization_id uuid, p_organization_address text, p_recipient text, p_source_wamid text, p_node_conversation_id text, p_event_id uuid, p_agent_id uuid DEFAULT NULL::uuid, p_routing_queue_id uuid DEFAULT NULL::uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  target public.conversations;
  existing_receipt public.chatbot_node_handoff_receipts;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_event_id::text, 117));
  select * into existing_receipt from public.chatbot_node_handoff_receipts where event_id = p_event_id;
  if found then
    if existing_receipt.organization_id <> p_organization_id then
      raise exception 'handoff event belongs to another organization' using errcode = '42501';
    end if;
    return existing_receipt.conversation_id;
  end if;
  if not exists (select 1 from public.organization_lifecycle where organization_id = p_organization_id and status = 'active') then
    raise exception 'organization is archived' using errcode = '42501';
  end if;
  if not exists (select 1 from public.chatbot_node_bridges where organization_id = p_organization_id
    and organization_address = p_organization_address and engine in ('transitioning', 'node')) then
    raise exception 'number is not managed by Node' using errcode = '23514';
  end if;
  -- The exact source message must have arrived; never infer a conversation
  -- from a different number or an older conversation for the same customer.
  select c.* into target from public.conversations c join public.messages m on m.conversation_id = c.id
    where c.organization_id = p_organization_id and c.organization_address = p_organization_address
      and c.contact_address = p_recipient and m.organization_id = p_organization_id
      and m.external_id = p_source_wamid and m.direction = 'incoming' for update of c;
  if not found then raise exception 'source customer message has not arrived' using errcode = '40001'; end if;
  if (p_agent_id is null) = (p_routing_queue_id is null) then
    raise exception 'exactly one handoff target is required' using errcode = '23514';
  end if;
  if p_routing_queue_id is not null then
    perform public.route_conversation_to_queue(target.id, p_routing_queue_id);
  else
    if not exists (select 1 from public.agents a where a.organization_id = p_organization_id
      and a.id = p_agent_id and not a.ai and a.user_id is not null
      and coalesce(a.extra->'invitation'->>'status', 'accepted') = 'accepted') then
      raise exception 'handoff requires an active tenant human agent' using errcode = '23514';
    end if;
    -- Reuse assignment constraints; clear old queue so a valid tenant agent
    -- isn't incorrectly rejected as a member of a previous routing queue.
    update public.conversations set routing_queue_id = null, assigned_agent_id = p_agent_id where id = target.id;
  end if;
  insert into public.chatbot_node_conversations(organization_id, organization_address, node_conversation_id, conversation_id)
    values (p_organization_id, p_organization_address, p_node_conversation_id, target.id)
    on conflict (organization_id, organization_address, node_conversation_id)
    do update set human_owned = true;
  insert into public.chatbot_node_handoff_receipts(event_id, organization_id, conversation_id)
    values(p_event_id, p_organization_id, target.id);
  return target.id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.sync_node_bridge_lifecycle()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  binding public.chatbot_node_bridges;
  operation_id uuid;
begin
  if old.status = new.status then return new; end if;
  for binding in select * from public.chatbot_node_bridges where organization_id = new.organization_id
    and engine <> 'native' for update loop
    -- Stop stale activation retries locally. Node's suspended flag rejects any
    -- old activation that arrives after the suspension acknowledgment.
    update public.chatbot_node_operations set status = 'failed', last_error = 'Superseded by organization lifecycle change'
      where organization_id = binding.organization_id and organization_address = binding.organization_address
        and status not in ('succeeded', 'failed');
    operation_id := gen_random_uuid();
    insert into public.chatbot_node_operations(request_id, organization_id, organization_address, action, phase, payload)
      values(operation_id, binding.organization_id, binding.organization_address,
        case when new.status = 'archived' then 'suspend' else 'restore' end,
        case when new.status = 'archived' then 'suspend' else 'restore' end, '{}');
    update public.chatbot_node_bridges set sync_status = 'pending', request_id = operation_id,
      engine = 'transitioning', updated_at = now()
      where organization_id = binding.organization_id and organization_address = binding.organization_address;
  end loop;
  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.prepare_chatbot_flow_execution(p_message_id uuid, p_flow_version_id uuid DEFAULT NULL::uuid, p_agent_id uuid DEFAULT NULL::uuid)
 RETURNS TABLE(outcome text, run_id uuid, run_lock_version bigint, run_is_new boolean, run_status text, run_current_node_id text, run_waiting_for text, run_variables jsonb, flow_definition jsonb)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  incoming public.messages;
  active_run public.chatbot_flow_runs;
  target_version public.chatbot_flow_versions;
  target_agent public.agents;
  target_conversation public.conversations;
  previous_message public.messages;
  has_active_run boolean := false;
begin
  select * into incoming
  from public.messages as message
  where message.id = p_message_id;

  if not found then
    raise exception using
      errcode = 'P0002',
      message = 'incoming chatbot message not found';
  end if;

  if incoming.direction <> 'incoming'::public.direction then
    raise exception using
      errcode = '23514',
      message = 'chatbot execution requires an incoming message';
  end if;

  if public.is_node_managed_number(incoming.organization_id, incoming.organization_address) then
    raise exception 'native execution is disabled for this number' using errcode = '23514';
  end if;

  select * into target_conversation
  from public.conversations as conversation
  where conversation.id = incoming.conversation_id
  for update;

  select * into active_run
  from public.chatbot_flow_runs as run
  where run.conversation_id = incoming.conversation_id
    and run.status in ('running', 'waiting')
  for update;

  has_active_run := found;

  if target_conversation.assigned_agent_id is not null then
    if has_active_run then
      update public.chatbot_flow_runs as run
      set
        status = 'handed_off',
        waiting_for = null,
        expires_at = null,
        ended_at = now()
      where run.id = active_run.id;
    end if;

    return query select
      'not_started'::text,
      null::uuid,
      null::bigint,
      false,
      null::text,
      null::text,
      null::text,
      null::jsonb,
      null::jsonb;
    return;
  end if;

  if has_active_run
    and active_run.status = 'waiting'
    and active_run.expires_at is not null
    and active_run.expires_at <= now()
  then
    update public.chatbot_flow_runs as run
    set
      status = 'expired',
      waiting_for = null,
      expires_at = null,
      ended_at = now()
    where run.id = active_run.id;

    has_active_run := false;
  end if;

  if has_active_run then
    if active_run.last_processed_message_id = incoming.id then
      return query select
        'duplicate'::text,
        active_run.id,
        active_run.lock_version,
        false,
        active_run.status,
        active_run.current_node_id,
        active_run.waiting_for,
        active_run.variables,
        null::jsonb;
      return;
    end if;

    if active_run.last_processed_message_id is not null then
      select * into previous_message
      from public.messages as message
      where message.id = active_run.last_processed_message_id;

      if found and (
        previous_message.created_at > incoming.created_at
        or (
          previous_message.created_at = incoming.created_at
          and previous_message.id >= incoming.id
        )
      ) then
        return query select
          'stale'::text,
          active_run.id,
          active_run.lock_version,
          false,
          active_run.status,
          active_run.current_node_id,
          active_run.waiting_for,
          active_run.variables,
          null::jsonb;
        return;
      end if;
    end if;

    select * into target_version
    from public.chatbot_flow_versions as version
    where version.id = active_run.flow_version_id;

    return query select
      'ready'::text,
      active_run.id,
      active_run.lock_version,
      false,
      active_run.status,
      active_run.current_node_id,
      active_run.waiting_for,
      active_run.variables,
      target_version.definition;
    return;
  end if;

  if p_flow_version_id is null or p_agent_id is null then
    return query select
      'not_started'::text,
      null::uuid,
      null::bigint,
      false,
      null::text,
      null::text,
      null::text,
      null::jsonb,
      null::jsonb;
    return;
  end if;

  select * into target_version
  from public.chatbot_flow_versions as version
  where version.id = p_flow_version_id
    and version.organization_id = incoming.organization_id
    and version.status = 'published';

  if not found then
    raise exception using
      errcode = '23514',
      message = 'chatbot execution requires a published flow version from the same organization';
  end if;

  select * into target_agent
  from public.agents as agent
  where agent.id = p_agent_id
    and agent.organization_id = incoming.organization_id
    and agent.ai = true;

  if not found then
    raise exception using
      errcode = '23514',
      message = 'chatbot execution requires an AI agent from the same organization';
  end if;

  insert into public.chatbot_flow_runs (
    organization_id,
    conversation_id,
    flow_version_id,
    agent_id,
    current_node_id
  ) values (
    incoming.organization_id,
    incoming.conversation_id,
    target_version.id,
    target_agent.id,
    target_version.definition->>'start_node_id'
  )
  returning * into active_run;

  return query select
    'ready'::text,
    active_run.id,
    active_run.lock_version,
    true,
    active_run.status,
    active_run.current_node_id,
    active_run.waiting_for,
    active_run.variables,
    target_version.definition;
end;
$function$
;

